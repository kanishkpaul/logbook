import Foundation
import GRDB
import LogbookCore
import Testing
@testable import LogbookPersistence

@Suite struct SchemaTests {
    @Test func migratesAndSeedsBuiltinMetrics() throws {
        let db = try AppDatabase.openInMemory()
        let keys = try db.read { try String.fetchAll($0, sql: "SELECT key FROM metric_definition ORDER BY key") }
        #expect(keys == ["active_kcal", "steps"])
        #expect(try db.read { try Schema.migrator.hasCompletedMigrations($0) })
    }

    /// Regenerates `schema.sql` so the current schema is always readable in the repo.
    @Test func regeneratesSchemaSQL() throws {
        let db = try AppDatabase.openInMemory()
        let sql = try db.read { try AppDatabase.schemaSQL($0) }
        let url = URL(filePath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appending(path: "schema.sql")
        let header = "-- Generated by SchemaTests.regeneratesSchemaSQL. Do not edit; change Schema.swift.\n\n"
        try (header + sql).write(to: url, atomically: true, encoding: .utf8)
        #expect(sql.contains("CREATE TABLE \"time_block\""))
        #expect(sql.contains("CREATE VIEW \"daily_facts\""))
    }

    @Test func noUniqueConstraintsBesidesPrimaryKeys() throws {
        let db = try AppDatabase.openInMemory()
        let offenders = try db.read { db in
            try String.fetchAll(db, sql: """
                SELECT m.name || '.' || il.name FROM sqlite_master m, pragma_index_list(m.name) il
                WHERE m.type = 'table' AND il."unique" = 1 AND il.origin <> 'pk'
                  AND m.name NOT LIKE 'grdb_%'
                """)
        }
        #expect(offenders.isEmpty)
    }

    @Test func oneRunningBlockPerKindIsEnforcedByTheDatabase() throws {
        let db = try AppDatabase.openInMemory()
        func insertRunning(_ id: String, kind: String) throws {
            try db.write { db in
                try db.execute(sql: """
                    INSERT INTO time_block (id, kind, start_utc, tz_identifier, logical_day, created_at, updated_at)
                    VALUES (?, ?, '2026-10-10 04:00:00.000', 'UTC', '2026-10-10', '2026-10-10 04:00:00.000', '2026-10-10 04:00:00.000')
                    """, arguments: [id, kind])
            }
        }
        try insertRunning("a", kind: "work")
        try insertRunning("b", kind: "sleep")
        #expect(throws: DatabaseError.self) { try insertRunning("c", kind: "work") }
    }

    @Test func endBeforeStartIsRejectedByTheDatabase() throws {
        let db = try AppDatabase.openInMemory()
        #expect(throws: DatabaseError.self) {
            try db.write { db in
                try db.execute(sql: """
                    INSERT INTO time_block (id, kind, start_utc, end_utc, tz_identifier, logical_day, created_at, updated_at)
                    VALUES ('x', 'work', '2026-10-10 05:00:00.000', '2026-10-10 04:00:00.000', 'UTC', '2026-10-10', '2026-10-10 04:00:00.000', '2026-10-10 04:00:00.000')
                    """)
            }
        }
    }
}
